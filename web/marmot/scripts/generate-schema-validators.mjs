// Generates plain-JavaScript validators for the JSON Schema meta-schemas the console checks schemas against. ajv normally compiles validators at runtime with new Function, which the console's Content-Security-Policy forbids, so they are compiled here, ahead of time, with ajv's standalone mode.
// Run after upgrading ajv: node scripts/generate-schema-validators.mjs
import fs from 'node:fs';
import path from 'node:path';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

const out = path.resolve('src/lib/schema/generated');
fs.mkdirSync(out, { recursive: true });

// The same options json.ts used, so a schema is judged exactly as ajv.compile judged it.
const ajv = new Ajv({
	allErrors: true,
	$data: true,
	strict: false,
	code: { source: true, esm: true }
});
addFormats(ajv);
const meta = ajv.getSchema(ajv.opts.defaultMeta ?? 'http://json-schema.org/draft-07/schema');
if (!meta) throw new Error('draft-07 meta-schema not found');
let code = standaloneCode(ajv, meta);
// Standalone output still pulls ajv's small runtime helpers in with require(), which a browser module cannot run; each becomes an import.
const imports = [];
code = code.replace(/require\("([^"]+)"\)(\.default)?/g, (_m, mod) => {
	const name = `runtime${imports.length}`;
	imports.push(
		`import * as ${name}Module from '${mod}';\nconst ${name} = ${name}Module.default?.default ?? ${name}Module.default ?? ${name}Module;`
	);
	return name;
});
code = imports.join('\n') + '\n' + code;
if (/\brequire\(|new Function|\beval\(/.test(code))
	throw new Error('generated validator still needs require, eval or new Function');
const header =
	'// Generated by scripts/generate-schema-validators.mjs. Do not edit.\n/* eslint-disable */\n// @ts-nocheck\n';
fs.writeFileSync(path.join(out, 'draft7Meta.js'), header + code);
console.log('wrote', path.join(out, 'draft7Meta.js'));
